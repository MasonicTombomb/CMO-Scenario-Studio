"""Write a project out as the CMO folder structure.

Layout (same pattern as the official Lua-driven scenarios and *If Russia Wins*)::

    <root>/
      README.md                          (folder / zip export only)
      Lua/<Folder>/
        Build_Scenario.lua               run once in the editor's Lua console
        Build_<VARIANT>.lua              one launcher per build variant
        LuaInit.lua                      loaded when the scenario loads
        Studio_Runtime.lua               helper library used by events
        <Script>.lua                     your scripts
        project.cmoproj                  the studio project (re-open to edit)
        README.txt                       build instructions
        .studio_manifest.json            files written by the studio (for clean re-exports)
      Scenarios/<Folder>/
        <Prefix>_Desc.html               [LOADDOC] scenario description
        <Prefix>_Desc_<VARIANT>.html     per-variant description (optional)
        <Prefix>_Briefing_<SIDE>.html    [LOADDOC] side briefings
        briefing_style_dark.css

Exporting into the CMO install folder only ever replaces files the studio wrote
(tracked in the manifest); your .scen files are never touched, and the previous
files are zipped to a backup first.
"""

from __future__ import annotations

import json
import zipfile
from dataclasses import dataclass, field
from datetime import datetime
from importlib import resources
from pathlib import Path
from typing import Optional

from .. import __version__
from ..model.project import Project
from . import html as H
from .compiler import compile_build_data, compile_reserves, compile_intercepts, compile_routes, page_names
from .lua_writer import lua_long_str, lua_str, lua_value

MANIFEST = ".studio_manifest.json"
RESERVED_SCRIPT_NAMES = {"build_scenario", "luainit", "studio_runtime"}


def _resource(name: str) -> str:
    return resources.files("cmo_studio.export").joinpath("lua", name).read_text(encoding="utf-8")


@dataclass
class ExportResult:
    root: Path
    written: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)
    backup: Optional[Path] = None
    warnings: list[str] = field(default_factory=list)


class Exporter:
    def __init__(self, project: Project):
        self.p = project

    # ------------------------------------------------------------------ paths
    @property
    def folder(self) -> str:
        return self.p.meta.folder()

    @property
    def lua_dir(self) -> str:
        return f"Lua/{self.folder}"

    @property
    def scen_dir(self) -> str:
        return f"Scenarios/{self.folder}"

    # ------------------------------------------------------------------ content
    def build_files(self, include_readme: bool = True) -> dict[str, str]:
        """All generated files: relative POSIX path -> text."""
        p = self.p
        files: dict[str, str] = {}
        L, S = self.lua_dir, self.scen_dir
        files[f"{L}/Build_Scenario.lua"] = self.build_scenario_lua()
        for v in p.variants:
            files[f"{L}/Build_{v.key}.lua"] = self.variant_launcher(v)
        files[f"{L}/LuaInit.lua"] = self.luainit_lua()
        files[f"{L}/Studio_Runtime.lua"] = _crlf(_resource("Studio_Runtime.lua"))
        for s in p.scripts:
            files[f"{L}/{s.name}.lua"] = _crlf(f"-- {s.name}.lua  ({p.meta.title})\n" + (
                f"-- {s.notes}\n" if s.notes else "") + s.content.rstrip() + "\n")
        files[f"{L}/project.cmoproj"] = p.to_json() + "\n"
        files[f"{L}/README.txt"] = _crlf(self.instructions_text())

        pages = page_names(p)
        files[f"{S}/{pages['desc']}"] = H.description_page(p)
        for v in p.variants:
            if v.description_html.strip():
                files[f"{S}/{pages['variants'][v.key]}"] = H.description_page(p, v)
        for side in p.sides:
            if side.name in pages["briefings"]:
                files[f"{S}/{pages['briefings'][side.name]}"] = H.briefing_page(p, side)
        files[f"{S}/{H.CSS_FILE}"] = H.crlf(H.BRIEFING_CSS)
        if include_readme:
            files["README.md"] = self.readme_md()
        return files

    def header_comment(self) -> str:
        p, m = self.p, self.p.meta
        pages = page_names(p)
        variants = "".join(
            f"      ScenEdit_RunScript('/{self.folder}/Build_{v.key}.lua')   -- {v.name}\n"
            f"        save as  Scenarios\\{self.folder}\\{m.title}{v.scen_suffix}.scen\n" for v in p.variants)
        return f"""--[[==========================================================================
  {m.title.upper()}
  Build_Scenario.lua - ONE-OFF builder. Places every side, unit, mission and event.
  Generated by CMO Scenario Studio {__version__} on {datetime.now():%Y-%m-%d %H:%M}.
  Edit the project (project.cmoproj) in the studio and export again rather than
  editing this file by hand.

  Database: {m.db_file or '(not set)'}    Start: {p.clock.start_dt():%d %b %Y %H:%M} Z    Duration: {p.clock.duration_text()}

  HOW TO USE
    1. Keep this folder at [CMO]\\Lua\\{self.folder}\\ and the pages at
       [CMO]\\Scenarios\\{self.folder}\\.
    2. CMO > Create New Blank Scenario{f' (database {m.db_file})' if m.db_file else ''}.
    3. Editor > Lua Script Console:
         ScenEdit_RunScript('/{self.folder}/Build_Scenario.lua')
       The console prints a BUILD REPORT with any warnings.
    4. Editor > Scenario Description:  [LOADDOC]{pages['desc']}[/LOADDOC]
       Editor > Side Briefing (per side):
{''.join(f"         {n}:  [LOADDOC]{f}[/LOADDOC]{chr(10)}" for n, f in pages['briefings'].items())}       Editor > Scenario Title: {m.title}{f'   Setting: {m.setting}' if m.setting else ''}
    5. Save as Scenarios\\{self.folder}\\{m.title}.scen
{('  VARIANTS (start each from a NEW blank scenario):' + chr(10) + variants) if p.variants else ''}
  The events call scripts in this folder at run time, so the folder must be
  present on the machine that runs the scenario.
============================================================================]]
"""

    def build_scenario_lua(self) -> str:
        D = compile_build_data(self.p)
        parts = [self.header_comment(), "", "local D = {}", ""]
        order = ("CFG", "PAGES", "SIDES", "POSTURES", "VARIANTS", "RPS", "ZONES", "UNITS", "FORMATIONS",
                 "MISSIONS", "KV", "FORECAST",
                 "EVENTS", "SPECIALS")
        # anything the compiler adds later is written too, so new build data cannot be left out by accident
        order += tuple(k for k in D if k not in order)
        for key in order:
            value = D[key]
            if isinstance(value, list):
                parts.append(f"D.{key} = {{")
                for item in value:
                    parts.append(f"  {lua_value(item, 2, 140, long_strings=True)},")
                parts.append("}")
            else:
                parts.append(f"D.{key} = {lua_value(value, 0, 140, long_strings=True)}")
            parts.append("")
        parts.append(_resource("Studio_Builder.lua"))
        return _crlf("\n".join(parts))

    def variant_launcher(self, v) -> str:
        return _crlf(f"""--[[ Build_{v.key}.lua - builds the "{v.name}" version of {self.p.meta.title}.
     Computer-controlled: {', '.join(self.p.side_name(x) for x in v.computer_sides) or '(none extra)'}
     In the Lua console of a NEW BLANK scenario run:
       ScenEdit_RunScript('/{self.folder}/Build_{v.key}.lua')
     then save it as Scenarios\\{self.folder}\\{self.p.meta.title}{v.scen_suffix}.scen ]]

STUDIO_BUILD_VARIANT = {lua_str(v.key)}
ScenEdit_RunScript('/{self.folder}/Build_Scenario.lua')
""")

    def luainit_lua(self) -> str:
        p = self.p
        init_scripts = [s for s in p.scripts if s.load_on_init]
        lines = [
            f"--[[ LuaInit.lua - {p.meta.title}",
            "     Run by the 'Scenario Loaded' event (and by any event script that finds it missing).",
            "     Generated by CMO Scenario Studio; edit the project and export again. ]]",
            "",
            "STUDIO = STUDIO or {}",
            f"STUDIO.TITLE = {lua_str(p.meta.title)}",
            f"STUDIO.PATH = {lua_str('/' + self.folder + '/')}",
            f"STUDIO.START = {p.clock.start_epoch()}",
            f"STUDIO.SIDES = {lua_value([s.name for s in p.sides])}",
            f"STUDIO.RESERVES = {lua_value(compile_reserves(p), 0, 140)}",
            f"STUDIO.ROUTES = {lua_value(compile_routes(p), 0, 140)}",
            f"STUDIO.INTERCEPTS = {lua_value(compile_intercepts(p), 0, 140)}",
            "",
            "local ok, err = pcall(ScenEdit_RunScript, STUDIO.PATH .. 'Studio_Runtime.lua')",
            "if not ok then print('[' .. STUDIO.TITLE .. '] Could not load Studio_Runtime.lua: ' .. tostring(err)) end",
            "if not STUDIO.SEEDED then math.randomseed(os.time()); STUDIO.SEEDED = true end",
            "",
        ]
        if init_scripts:
            lines.append("-- Project scripts marked 'load on init'")
            for s in init_scripts:
                lines.append(f"StudioRunScript({lua_str(s.name)})")
            lines.append("")
        lines.append("STUDIO_LUAINIT_LOADED = true")
        return _crlf("\n".join(lines) + "\n")

    def instructions_text(self) -> str:
        p = self.p
        pages = page_names(p)
        lines = [
            f"{p.meta.title} - build instructions",
            "=" * 60,
            "",
            f"1. Copy Lua\\{self.folder}\\ and Scenarios\\{self.folder}\\ into your CMO folder",
            "   (the studio's 'Install into CMO' export does this for you).",
            f"2. In CMO: Create New Blank Scenario{f' using {p.meta.db_file}' if p.meta.db_file else ''}.",
            "3. Editor > Lua Script Console, run:",
            f"     ScenEdit_RunScript('/{self.folder}/Build_Scenario.lua')",
            "4. Editor > Scenario Description:",
            f"     [LOADDOC]{pages['desc']}[/LOADDOC]",
            "   Editor > Side Briefing, for each side:",
        ]
        lines += [f"     {n}: [LOADDOC]{f}[/LOADDOC]" for n, f in pages["briefings"].items()]
        lines += [f"5. Save as Scenarios\\{self.folder}\\{p.meta.title}.scen", ""]
        if p.variants:
            lines.append("Variants (start each from a new blank scenario):")
            for v in p.variants:
                lines.append(f"  ScenEdit_RunScript('/{self.folder}/Build_{v.key}.lua')  -> "
                             f"{p.meta.title}{v.scen_suffix}.scen  (description "
                             f"[LOADDOC]{pages['variants'][v.key]}[/LOADDOC])")
            lines.append("")
        lines += ["Tip: DebugModeIsOn / STUDIO.DEBUG = true in the console prints extra detail from events.", ""]
        return "\n".join(lines)

    def readme_md(self) -> str:
        p, m = self.p, self.p.meta
        return f"""# {m.title}

A scenario for *Command: Modern Operations*, made with CMO Scenario Studio.

{('**Setting:** ' + m.setting + '  ') if m.setting else ''}
**Start:** {p.clock.start_dt():%d %B %Y %H:%M} Z · **Duration:** {p.clock.duration_text()}
{('· **Database:** ' + m.db_file) if m.db_file else ''}

## Install

Copy both folders into your CMO install folder (for Steam usually
`...\\steamapps\\common\\Command - Modern Operations\\`):

```
Lua\\{self.folder}\\
Scenarios\\{self.folder}\\
```

## Build the .scen

See `Lua/{self.folder}/README.txt`. In short: create a new blank scenario, open the
Lua Script Console and run

```lua
ScenEdit_RunScript('/{self.folder}/Build_Scenario.lua')
```

then set the description/briefings with the `[LOADDOC]` lines the build report prints, and save.

## Edit

Open `Lua/{self.folder}/project.cmoproj` in CMO Scenario Studio.
"""

    # ------------------------------------------------------------------ writing
    def preflight(self, root: str | Path) -> tuple[list[Path], bool]:
        """(existing files that would be overwritten, whether the studio wrote this folder before)."""
        root = Path(root)
        files = self.build_files(include_readme=False)
        existing = [root / rel for rel in files if (root / rel).exists()]
        managed = (root / self.lua_dir / MANIFEST).is_file()
        return existing, managed

    def write(self, root: str | Path, backup_dir: Optional[str | Path] = None, clean: bool = True,
              include_readme: bool = True) -> ExportResult:
        """Write into ``root`` (a CMO install folder or any folder)."""
        root = Path(root)
        files = self.build_files(include_readme=include_readme)
        res = ExportResult(root=root)
        lua_dir = root / self.lua_dir
        manifest_path = lua_dir / MANIFEST
        old: list[str] = []
        if manifest_path.is_file():
            try:
                old = json.loads(manifest_path.read_text(encoding="utf-8")).get("files", [])
            except (ValueError, OSError):
                old = []
        targets = [root / rel for rel in files]
        existing = [t for t in targets if t.exists()] + [root / rel for rel in old if (root / rel).exists()]
        if backup_dir and existing:
            res.backup = self._backup(root, sorted(set(existing)), Path(backup_dir))
        for rel, text in files.items():
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="")
            res.written.append(path)
        if clean:
            for rel in old:
                if rel not in files and (root / rel).is_file():
                    (root / rel).unlink()
                    res.removed.append(root / rel)
        manifest = {"generator": f"CMO Scenario Studio {__version__}", "written": datetime.now().isoformat(
            timespec="seconds"), "files": sorted(files)}
        manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        return res

    def write_zip(self, zip_path: str | Path) -> Path:
        zip_path = Path(zip_path)
        top = self.folder
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
            for rel, text in self.build_files().items():
                z.writestr(f"{top}/{rel}", text.encode("utf-8"))
        return zip_path

    def _backup(self, root: Path, paths: list[Path], backup_dir: Path) -> Path:
        backup_dir.mkdir(parents=True, exist_ok=True)
        zpath = backup_dir / f"{self.folder}_{datetime.now():%Y%m%d_%H%M%S}.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for p in paths:
                if p.is_file():
                    z.write(p, p.relative_to(root).as_posix())
        return zpath


def _crlf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\n", "\r\n")


