local function unitName(u, i)
  if (u.count or 1) > 1 then return string.format('%s #%d', u.name, i) end
  return u.name
end

local function nameOf(id)
  for _, v in ipairs(D.UNITS) do if v.id == id then return v.name end end
  return tostring(id)
end

-- An aircraft that starts at a base. CMO refuses (with a .NET exception) when the base has no hangar, shelter or
-- parking for it - a runway or tower picked as the base, a shelter that is too small or already full. Try the base,
-- then the other aircraft facilities of the same site (u.alts); at each, the chosen loadout first and the reserve
-- loadout second. Only report a refused loadout when the reserve loadout really was what made it work.
local function addAircraftAtBase(u, name, spec, hostGuid)
  local loadout = spec.loadoutid
  local cands = { { id = u.host, guid = hostGuid } }
  for _, aid in ipairs(u.alts or {}) do
    local g = B.guids[aid] and B.guids[aid][1]
    if g then cands[#cands + 1] = { id = aid, guid = g } end
  end
  local firstErr
  for i, c in ipairs(cands) do
    spec.base = c.guid
    spec.loadoutid = loadout
    local ok, res = try(ScenEdit_AddUnit, spec)
    local reserve = false
    if not (ok and res) then
      firstErr = firstErr or res
      if loadout ~= D.CFG.DEFAULT_LOADOUT then
        spec.loadoutid = D.CFG.DEFAULT_LOADOUT
        ok, res = try(ScenEdit_AddUnit, spec)
        reserve = ok and res and true or false
      end
    end
    if ok and res then
      if i > 1 then
        warn(string.format('%s: %s cannot take it, based at %s instead', name, nameOf(u.host), nameOf(c.id)))
      end
      if reserve then
        warn(string.format('%s: loadout %s refused, placed in reserve instead', name, tostring(loadout)))
      end
      return true, res
    end
  end
  local others = #cands > 1 and string.format(' (nor the %d other aircraft facilities of its site)', #cands - 1) or ''
  return false, string.format('%s cannot base it%s: it needs a hangar, shelter or parking with room for this ' ..
    'aircraft - a runway, taxiway or tower cannot hold aircraft. CMO said: %s', nameOf(u.host), others,
    tostring(firstErr))
end

local function addOne(u, i)
  local name = unitName(u, i)
  local spec = { side = u.side, type = u.type, dbid = u.dbid, name = name }
  local hostGuid = u.host and B.guids[u.host] and B.guids[u.host][1] or nil
  if u.host and not hostGuid then warn(name .. ': host was not built, placed at its own position') end
  if hostGuid then
    spec.base = hostGuid
  else
    spec.latitude, spec.longitude = u.lat, u.lon
    if u.type == 'Aircraft' then spec.altitude = u.alt or 9000 end
  end
  if u.type == 'Aircraft' then
    spec.loadoutid = (D.CFG.ARMED_START and u.loadout) or D.CFG.DEFAULT_LOADOUT
  end
  if u.type == 'Submarine' and u.depth then spec.depth = u.depth end
  if u.heading then spec.heading = u.heading end

  local ok, res
  if u.type == 'Aircraft' and hostGuid then
    ok, res = addAircraftAtBase(u, name, spec, hostGuid)
  else
    ok, res = try(ScenEdit_AddUnit, spec)
  end
  if (not ok or not res) and spec.base and u.type ~= 'Aircraft' then
    -- boats and vehicles: fall back to the host's position
    local h = select(2, try(ScenEdit_GetUnit, { guid = hostGuid }))
    spec.base = nil
    if h then spec.latitude, spec.longitude = h.latitude, h.longitude else spec.latitude, spec.longitude = u.lat, u.lon end
    ok, res = try(ScenEdit_AddUnit, spec)
  end
  if (not ok or not res) and u.type == 'Submarine' then
    spec.depth = nil; ok, res = try(ScenEdit_AddUnit, spec)
    if not ok or not res then spec.type = 'Sub'; ok, res = try(ScenEdit_AddUnit, spec) end
  end
  if (not ok or not res) and u.type == 'GroundUnit' then
    spec.type = 'Facility'; ok, res = try(ScenEdit_AddUnit, spec)
  end
  if (not ok or not res) and u.type == 'Aircraft' and not hostGuid and spec.loadoutid ~= D.CFG.DEFAULT_LOADOUT then
    -- airborne aircraft: retry with the reserve loadout, and only blame the loadout if that works
    local refused = spec.loadoutid
    spec.loadoutid = D.CFG.DEFAULT_LOADOUT
    local ok2, res2 = try(ScenEdit_AddUnit, spec)
    if ok2 and res2 then
      warn(string.format('%s: loadout %s refused, placed in reserve instead', name, tostring(refused)))
      ok, res = ok2, res2
    end
  end
  if not ok or not res then
    B.failed[#B.failed + 1] = string.format('%s (%s %s, dbid %s): %s', name, u.side, u.type, tostring(u.dbid), tostring(res))
    log(1, 'FAILED  %s', B.failed[#B.failed])
    return nil
  end
  local guid = res.guid
  log(2, 'added   %-10s %-9s %s [dbid %d -> %s]', u.side, u.type, name, u.dbid, tostring(res.classname or '?'))
  count(u.side .. ' ' .. u.type)

  if u.radar then try(ScenEdit_SetEMCON, 'Unit', guid, 'Radar=Active') end
  if u.sonar then try(ScenEdit_SetEMCON, 'Unit', guid, 'Sonar=Active') end
  if u.hold then try(ScenEdit_SetUnit, { guid = guid, HoldPosition = true }) end
  if u.auto then try(ScenEdit_SetUnit, { guid = guid, autodetectable = true }) end
  if u.prof then
    local okP, errP = try(ScenEdit_SetUnit, { guid = guid, proficiency = u.prof })
    if not okP then warn(name .. ': proficiency ' .. tostring(errP)) end
  end
  if u.speed then
    if not try(ScenEdit_SetUnit, { guid = guid, manualSpeed = u.speed }) then
      try(ScenEdit_SetUnit, { guid = guid, speed = u.speed })
    end
  end
  if u.set then
    local fields = { guid = guid }
    for k, v in pairs(u.set) do fields[k] = v end
    local okX, errX = try(ScenEdit_SetUnit, fields)
    if not okX then warn(name .. ': extra unit fields: ' .. tostring(errX)) end
  end
  return guid
end

local function buildUnits()
  for n, u in ipairs(D.UNITS) do
    if n % 25 == 1 then log(1, 'Units %d-%d of %d...', n, math.min(n + 24, #D.UNITS), #D.UNITS) end
    B.guids[u.id] = {}
    for i = 1, (u.count or 1) do
      local g = addOne(u, i)
      if g then table.insert(B.guids[u.id], g) end
    end
    B.names[u.id] = unitName(u, 1)
  end
end

------------------------------------------------------------------ formations
-- As in the official scenarios: unit.group = 'Name' groups a unit, and
-- ScenEdit_SetUnit({guid=, formation={bearing=, distance=}}) sets its station
-- relative to the group lead. Units are already on their stations, so if
-- grouping is refused the layout is still right and the report says so.
local function setGroup(guid, name)
  local ok, u = try(ScenEdit_GetUnit, { guid = guid })
  if not ok or not u then return false end
  return (pcall(function() u.group = name end))
end

local function buildFormations()
  for _, f in ipairs(D.FORMATIONS or {}) do
    local lead = B.guids[f.lead] and B.guids[f.lead][1]
    if not lead then
      warn('Formation "' .. f.name .. '": its lead was not built')
    elseif not setGroup(lead, f.name) then
      warn('Formation "' .. f.name .. '": units are on station but could not be grouped from Lua - select them ' ..
           'in the editor and group them.')
    else
      local placed = 0
      for _, m in ipairs(f.members) do
        local g = B.guids[m.id] and B.guids[m.id][1]
        if g and setGroup(g, f.name) and f.nostations then
          placed = placed + 1     -- a site: grouped, no formation station
        elseif g and setGroup(g, f.name) then
          local full = { bearing = m.bearing, distance = m.dist, type = f.stype, sprint = f.sprint }
          if try(ScenEdit_SetUnit, { guid = g, formation = full })
             or try(ScenEdit_SetUnit, { guid = g, formation = { bearing = m.bearing, distance = m.dist } }) then
            placed = placed + 1
          else
            warn('Formation "' .. f.name .. '": station for ' .. tostring(B.names[m.id]) .. ' not set')
          end
        elseif g then
          warn('Formation "' .. f.name .. '": could not add ' .. tostring(B.names[m.id]) .. ' to the group')
        end
      end
      count('formations')
      log(2, 'group   %-30s lead %s, %d/%d station(s)', f.name, tostring(B.names[f.lead]), placed, #f.members)
    end
  end
end

------------------------------------------------------------------ missions
local function buildMissions()
  for _, m in ipairs(D.MISSIONS) do
    local opts = {}
    if m.sub then opts.type = m.sub end
    if m.zone then
      opts.zone = B.zoneNames[m.zone]
      if not opts.zone then warn('Mission "' .. m.name .. '": its area was not built') end
    end
    if m.dest then opts.destination = B.guids[m.dest] and B.guids[m.dest][1] or B.names[m.dest] end
    local ok, res = try(ScenEdit_AddMission, m.side, m.name, m.class, opts)
    if not ok or not res then
      warn('Mission "' .. m.name .. '" not created: ' .. tostring(res))
    else
      count('missions')
      if m.opts and next(m.opts) then
        local okO, errO = try(ScenEdit_SetMission, m.side, m.name, m.opts)
        if not okO then
          -- apply one by one so a single unsupported field does not lose the rest
          for k, v in pairs(m.opts) do
            local okK, errK = try(ScenEdit_SetMission, m.side, m.name, { [k] = v })
            if not okK then warn('Mission "' .. m.name .. '" option ' .. k .. ': ' .. tostring(errK)) end
          end
        end
      end
      if m.pzone and B.zoneNames[m.pzone] then
        local z = B.zoneNames[m.pzone]
        if not try(ScenEdit_SetMission, m.side, m.name, { prosecutionzone = z }) then
          if not try(ScenEdit_SetMission, m.side, m.name, { ProsecutionZone = z }) then
            warn('Mission "' .. m.name .. '": prosecution zone not set - add it in the mission editor.')
          end
        end
      end
      local na = 0
      for _, uid in ipairs(m.units or {}) do
        for _, g in ipairs(B.guids[uid] or {}) do
          if try(ScenEdit_AssignUnitToMission, g, m.name) then na = na + 1
          else warn('Could not assign ' .. tostring(B.names[uid]) .. ' to "' .. m.name .. '"') end
        end
      end
      local nt = 0
      for _, uid in ipairs(m.targets or {}) do
        for _, g in ipairs(B.guids[uid] or {}) do
          if try(ScenEdit_AssignUnitAsTarget, g, m.name) then nt = nt + 1
          else warn('Could not add target ' .. tostring(B.names[uid]) .. ' to "' .. m.name .. '"') end
        end
      end
      log(2, 'mission %-10s %-30s %s/%s, %d unit(s), %d target(s)', m.side, m.name, m.class, tostring(m.sub), na, nt)
    end
  end
end

------------------------------------------------------------------ events
local BOOT = "if not STUDIO_LUAINIT_LOADED then ScenEdit_RunScript('" .. D.CFG.PATH .. "LuaInit.lua') end\n"

local function resolveSpec(spec, t)
  local s = {}
  for k, v in pairs(spec) do s[k] = v end
  if t.unit then
    s.TargetFilter = s.TargetFilter or {}
    local g = B.guids[t.unit] and B.guids[t.unit][1]
    if g then s.TargetFilter.SpecificUnitID = g else warn('Trigger "' .. t.name .. '": unit was not built') end
  end
  if t.area then
    s.Area = B.zoneNames[t.area]
    if not s.Area then warn('Trigger "' .. t.name .. '": area was not built') end
  end
  return s
end

local function buildEvents()
  for _, e in ipairs(D.EVENTS) do
    local ok = try(ScenEdit_SetEvent, e.name, { mode = 'add', IsRepeatable = e.repeatable, IsActive = e.active,
                                                IsShown = e.shown })
    if not ok then
      ok = try(ScenEdit_SetEvent, e.name, { mode = 'add', IsRepeatable = e.repeatable and 1 or 0,
                                            IsActive = e.active and 1 or 0, IsShown = e.shown and 1 or 0 })
    end
    if not ok then
      warn('Event "' .. e.name .. '" could not be created.')
    else
      count('events')
      local attached = 0
      for _, t in ipairs(e.triggers) do
        local spec = resolveSpec(t.spec, t)
        spec.mode, spec.name = 'add', t.name
        local okT, err = try(ScenEdit_SetTrigger, spec)
        if okT then
          if try(ScenEdit_SetEventTrigger, e.name, { mode = 'add', name = t.name }) then attached = attached + 1 end
        else
          warn('Trigger "' .. t.name .. '": ' .. tostring(err))
        end
      end
      if attached == 0 then warn('Event "' .. e.name .. '" has no trigger - add one in the event editor.') end
      for _, c in ipairs(e.conditions or {}) do
        local spec = resolveSpec(c.spec, c)
        spec.mode, spec.name = 'add', c.name
        if try(ScenEdit_SetCondition, spec) then
          try(ScenEdit_SetEventCondition, e.name, { mode = 'add', name = c.name })
        else
          warn('Condition "' .. c.name .. '" could not be created.')
        end
      end
      if e.script and e.script ~= '' then
        local an = e.name .. ' (script)'
        local okS, errS = try(ScenEdit_SetAction, { mode = 'add', type = 'LuaScript', name = an,
                                                    ScriptText = crlf(BOOT .. e.script) })
        if okS then try(ScenEdit_SetEventAction, e.name, { mode = 'add', name = an })
        else warn('Action "' .. an .. '": ' .. tostring(errS)) end
      end
      for _, a in ipairs(e.actions or {}) do
        local spec = {}
        for k, v in pairs(a.spec) do spec[k] = v end
        spec.mode, spec.name = 'add', a.name
        if try(ScenEdit_SetAction, spec) then
          try(ScenEdit_SetEventAction, e.name, { mode = 'add', name = a.name })
        else
          warn('Native action "' .. a.name .. '" could not be created.')
        end
      end
      log(2, 'event   "%s": %d/%d trigger(s)', e.name, attached, #e.triggers)
    end
  end
end

local function buildSpecials()
  for _, a in ipairs(D.SPECIALS) do
    if COMPUTER[a.side] then
      log(2, 'special "%s" skipped: %s is computer-controlled', a.name, a.side)
    else
      local ok, err = try(ScenEdit_AddSpecialAction, {
        ActionNameOrID = a.name, Description = a.desc, Side = a.side,
        IsActive = a.active, IsRepeatable = a.repeatable, ScriptText = crlf(BOOT .. a.script) })
      if ok then count('special actions') else warn('Special action "' .. a.name .. '": ' .. tostring(err)) end
    end
  end
end

local function buildKeyValues()
  for _, kv in ipairs(D.KV) do try(ScenEdit_SetKeyValue, kv[1], kv[2]) end
  try(ScenEdit_SetKeyValue, 'STUDIO_VARIANT', VARIANT_KEY or '')
  for _, e in ipairs(D.EVENTS) do try(ScenEdit_SetKeyValue, 'STUDIO_EVT_' .. e.key, '') end
end

------------------------------------------------------------------ report
local function report()
  local lines = { '', '==================== BUILD REPORT: ' .. D.CFG.TITLE .. ' ====================' }
  local function add(s) lines[#lines + 1] = s end
  add('Version: ' .. (VARIANT and (VARIANT.name .. ' [' .. VARIANT_KEY .. ']') or 'Standard'))
  local keys = {}
  for k in pairs(B.added) do keys[#keys + 1] = k end
  table.sort(keys)
  for _, k in ipairs(keys) do add(string.format('  %-34s %d', k, B.added[k])) end
  if #B.failed > 0 then
    add(string.format('FAILED UNITS (%d):', #B.failed))
    for _, f in ipairs(B.failed) do add('  ' .. f) end
  end
  if #B.warn > 0 then
    add(string.format('WARNINGS (%d):', #B.warn))
    for _, w in ipairs(B.warn) do add('  ' .. w) end
  end
  add('')
  add('NEXT STEPS (Editor menu):')
  add('  Scenario Description:  [LOADDOC]' .. ((VARIANT and VARIANT.desc) or D.PAGES.desc) .. '[/LOADDOC]')
  for _, s in ipairs(D.SIDES) do
    if D.PAGES.briefings[s.name] then
      add('  Side briefing for ' .. s.name .. ':  [LOADDOC]' .. D.PAGES.briefings[s.name] .. '[/LOADDOC]')
    end
  end
  add('  Scenario Title:  ' .. ((VARIANT and VARIANT.scen) or D.CFG.TITLE))
  if D.CFG.SETTING ~= '' then add('  Scenario Setting:  ' .. D.CFG.SETTING) end
  add('  Save as:  Scenarios\\' .. D.CFG.FOLDER .. '\\' .. ((VARIANT and VARIANT.scen) or D.CFG.TITLE) .. '.scen')
  add(string.format('Built in %.1f s.', os.clock() - B.t0))
  print(table.concat(lines, '\n'))
end

------------------------------------------------------------------ main
local function build()
  print('[Build] ' .. D.CFG.TITLE .. ' - building ' .. (VARIANT and VARIANT.name or 'standard version'))
  if not D.CFG.FORCE_REBUILD then
    for _, s in ipairs(D.SIDES) do
      if sideUnitCount(s.name) > 0 then
        print('[Build] Side "' .. s.name .. '" already has units. Start from a new blank scenario, or set ' ..
              'FORCE_REBUILD = true in D.CFG to build on top of it.')
        return false
      end
    end
  end
  -- The runtime library must be loaded for event scripts that run straight after the build.
  STUDIO_LUAINIT_LOADED = nil
  try(ScenEdit_RunScript, D.CFG.PATH .. 'LuaInit.lua')

  log(1, 'Sides...');            buildSides()
  log(1, 'Clock and weather...'); buildClock()
  log(1, 'Reference points...'); buildPoints()
  log(1, 'Units...');            buildUnits()
  log(1, 'Formations...');       buildFormations()
  log(1, 'Missions...');         buildMissions()
  log(1, 'Key values...');       buildKeyValues()
  log(1, 'Events...');           buildEvents()
  log(1, 'Special actions...');  buildSpecials()
  report()
  return true
end

local ok, err = pcall(build)
if not ok then print('[Build] ABORTED: ' .. tostring(err)) end
