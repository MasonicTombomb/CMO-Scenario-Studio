local function buildClock()
  local s = D.CFG.START
  local time = string.format('%02d.%02d.%02d', s.hour, s.min, s.sec)
  local dur = string.format('%d:%d:%d', D.CFG.DURATION.d, D.CFG.DURATION.h, D.CFG.DURATION.m)
  local mdy = string.format('%d.%d.%d', s.month, s.day, s.year)
  local dmy = string.format('%d.%d.%d', s.day, s.month, s.year)
  local ok = try(ScenEdit_SetStartTime, { Date = mdy, Time = time, Duration = dur })
  if not ok then ok = try(ScenEdit_SetStartTime, { Date = dmy, Time = time, Duration = dur }) end
  local ok2 = try(ScenEdit_SetTime, { Date = mdy, Time = time })
  if not ok2 then ok2 = try(ScenEdit_SetTime, { Date = dmy, Time = time }) end
  if not (ok or ok2) then
    warn(string.format('Could not set the clock from Lua. Editor > Scenario Times: start %04d-%02d-%02d %s Z, duration %s.',
      s.year, s.month, s.day, time, dur))
  end
  local w = D.CFG.WEATHER
  local okW, errW = try(ScenEdit_SetWeather, w.temp, w.rain, w.cloud, w.sea)
  if not okW then warn('Weather: ' .. tostring(errW)) end
  local okT, t = try(ScenEdit_CurrentTime)
  t = (okT and tonumber(t)) or 0
  if t > 0 and os and os.date then
    log(1, 'Scenario clock now reads %s Z (expected %04d-%02d-%02d %02d:%02d)', os.date('!%Y-%m-%d %H:%M', t),
      s.year, s.month, s.day, s.hour, s.min)
  end
end

